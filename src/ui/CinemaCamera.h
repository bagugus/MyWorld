#include <optional>

namespace lw {

class CameraController;

namespace ui {

// Оператор кино (этап 12а.7): из плана кадра режиссёра (ShotPlan — общий,
// средний, крупный; что уместить) ставит кадр кинокамеры в 3D (CinemaShot):
// откуда смотреть, каким объективом, как плавно.
//   крупный — герой в три четверти спереди-сбоку (сторона — по id героя, чтобы
//             его всегда снимали одинаково); камера переставляется, только
//             когда он заметно отвернулся;
//   средний — все в кадре; двое — сбоку от линии между ними;
//   общий   — сверху и издалека, неподвижно.
// Камера не двигается без причины (12а.10): никаких облётов и кружения —
// статичный кадр или движение за героем (якорь кадра держится жёстко, так что
// он не убегает из кадра и на большой скорости времени; курс меняется, только
// когда герой совсем отвернулся или пара разошлась по другой оси), наезд к
// важному (в кульминации объектив медленно сужается), отъезд в финале (конец
// эпизода, гибель героя в кадре). Далёкая смена кадра — склейка с короткой
// проявкой из чёрного вместо перелёта; близкая — плавный переход.
//
//   кадр-пауза (ShotPlan::vista, 12а.9) — низко, вдаль, неподвижно.
// Ракурсы и композиция (правило третей, 180°, нижний ракурс) — этап 12а.12.
class CinemaCamera {
public:
    // Режим «Сериал» включили: первый кадр — склейкой.
    void reset();
    // Сменился кадр (герой или линия): далеко — склейка.
    void cut() { pendingCut_ = true; }
    // Раз за кадр: поставить кадр камеры. heading — куда обращён герой
    // (atan2(dx, dy), как у моделей), если известно; climax — вот-вот
    // кульминация; finale — финал, камера отъезжает; dt — реальные секунды.
    void update(CameraController& camera, const ShotPlan& plan, std::optional<float> heading, bool climax,
                bool finale, float dt);

    // Затемнение после склейки: 1 — чёрный кадр, 0 — нет.
    float blackout() const { return blackout_; }
    // Насколько сужен объектив в кульминации (1 — нет).
    float pushIn() const { return pushIn_; }
    // Насколько камера отъехала в финале (1 — нет).
    float pullOut() const { return pullOut_; }

private:
    bool pendingCut_ = true;
    bool started_ = false;
    float yaw_ = 0.0f;  // курс камеры (градусы, как у орбиты)
    float side_ = 1.0f; // с какой стороны от героя снимать крупно: +1 / −1
    float pushIn_ = 1.0f;
    float pullOut_ = 1.0f;
    float blackout_ = 0.0f;
    float settle_ = 0.0f; // секунд плавного перехода после близкой смены кадра
    float blocked_ = 0.0f; // секунд, как вид заслонён (камера поднялась над препятствием)
    float dodgeRest_ = 0.0f; // секунд до следующего возможного обхода
    bool dodged_ = false;  // курс выбран в обход препятствия: до склейки за взглядом героя не поворачивать
};

} // namespace ui
} // namespace lw

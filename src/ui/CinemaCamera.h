// Оператор кино (этап 12а.7): из плана кадра режиссёра (ShotPlan — общий,
// средний, крупный; что уместить) ставит кадр кинокамеры в 3D (CinemaShot):
// откуда смотреть, каким объективом, как плавно.
//   крупный — герой в три четверти спереди-сбоку (сторона — по id героя, чтобы
//             его всегда снимали одинаково); камера переставляется, только
//             когда он заметно отвернулся;
//   средний — все в кадре; двое — сбоку от линии между ними;
//   общий   — сверху и издалека, неподвижно.
// Камера не двигается без причины (12а.10): никаких облётов и кружения —
// статичный кадр или движение за героем (якорь кадра держится жёстко, так что
// он не убегает из кадра и на большой скорости времени; курс меняется, только
// когда герой совсем отвернулся или пара разошлась по другой оси), наезд к
// важному (в кульминации объектив медленно сужается), отъезд в финале (конец
// эпизода, гибель героя в кадре). Далёкая смена кадра — склейка с короткой
// проявкой из чёрного вместо перелёта; близкая — плавный переход.
//
//   кадр-пауза (ShotPlan::vista, 12а.9) — низко, вдаль, неподвижно, горизонт
//             на нижней трети.
//   в комнате (ShotPlan::indoor, 12а.14) — камера внутри дома: курс, где в
//             комнате хватает места, ближе к трём четвертям спереди героя;
//             неподвижно, пока герой не пересел (тогда — склейка встык).
//
// Ракурсы и композиция (12а.12) — по смыслу сцены (ShotPlan::sense):
//   разговор — «восьмёрка»: двойной план, потом через плечо одного на другого
//              и обратно, встык; камера — по одну сторону линии между ними;
//   погоня   — проезд сбоку: камера идёт вровень с бегущим, свободное место —
//              перед ним, в панике кадр наклонён (голландский угол);
//   драка    — двойной план сбоку от линии, чуть снизу; издалека — через
//              плечо стрелка;
//   засада   — через плечо того, кто подкрадывается, на ничего не подозревающего;
//   угроза   — нижний ракурс: угроза нависает (через плечо героя на неё; герой
//              сам угроза — снизу на него);
//   горе, беспомощность — верхний ракурс, медленный наезд;
//   быт      — крупно в три четверти или панорама с места, мимо которого он идёт;
//   дома     — разговор за столом через плечо, кадр «через проём» из соседней комнаты.
// Правило третей: герой — на третьей линии, свободное место — по взгляду и
// движению, глаза — на верхней трети. Правило 180°: пары держат свои стороны
// кадра, направление движения героя по экрану сохраняется между склейками
// (ScreenMemory).
class CinemaCamera {
public:
    // Режим «Сериал» включили: первый кадр — склейкой.
    void reset();
    // Сменился кадр (герой или линия): далеко — склейка.
    void cut() { pendingCut_ = true; }
    // Раз за кадр: поставить кадр камеры. heading — куда обращён герой
    // (atan2(dx, dy), как у моделей), если известно; climax — вот-вот
    // кульминация; finale — финал, камера отъезжает; hidden — кадр закрыт
    // чёрным (титр, скачок): камера встаёт на место сразу, без перехода, —
    // когда кадр проявится, она уже стоит; dt — реальные секунды.
    void update(CameraController& camera, const ShotPlan& plan, std::optional<float> heading, bool climax,
                bool finale, float dt, bool hidden = false);

    // Затемнение после склейки: 1 — чёрный кадр, 0 — нет.
    float blackout() const { return blackout_; }
    // Насколько сужен объектив в кульминации (1 — нет).
    float pushIn() const { return pushIn_; }
    // Насколько камера отъехала в финале (1 — нет).
    float pullOut() const { return pullOut_; }
    // Каким приёмом снят кадр сейчас (для окна режиссёра).
    const char* framingTitle() const;
    // Смысл сцены, по которому снят кадр.
    SceneSense sense() const { return sense_; }

private:
    // Каким приёмом снят кадр.
    enum class Framing : std::uint8_t {
        Standard, // крупный, средний, общий, пауза, передний план и даль
        TwoShot,
        OverShoulder,
        Reverse,  // через плечо героя на собеседника
        Tracking,
        Pan,
        Low,
        High,
        Doorway,
        Indoor
    };

    // Глаз — в точке мира eye на высоте eyeY (мир), смотрит на look (высота
    // lookY, мир); якорь кадра — anchor. Курс, наклон, расстояние и смещение.
    static void aimFrom(CinemaShot& shot, Vector2 anchor, Vector2 eye, float eyeY, Vector2 look, float lookY);
    // Смысл сцены сменился и держится — принять (кадр строится заново).
    bool adoptSense(const ShotPlan& plan, float dt, bool cutting);

    ScreenMemory memory_;
    bool pendingCut_ = true;
    bool started_ = false;
    float yaw_ = 0.0f;  // курс камеры (градусы, как у орбиты)
    float side_ = 1.0f; // с какой стороны от героя снимать крупно: +1 / −1
    float pushIn_ = 1.0f;
    float pullOut_ = 1.0f;
    float blackout_ = 0.0f;
    float settle_ = 0.0f; // секунд плавного перехода после близкой смены кадра
    float blocked_ = 0.0f; // секунд, как вид заслонён (камера поднялась над препятствием)
    float dodgeRest_ = 0.0f; // секунд до следующего возможного обхода
    bool dodged_ = false;  // курс выбран в обход препятствия: до склейки за взглядом героя не поворачивать
    bool indoor_ = false;  // прошлый кадр — в комнате
    std::uint64_t stage_ = 0;

    // Композиция (12а.12).
    SceneSense sense_ = SceneSense::Daily; // принятый смысл
    EntityId other_ = kInvalidId;          // с кем сцена (принятый)
    SceneSense pendingSense_ = SceneSense::Daily;
    EntityId pendingOther_ = kInvalidId;
    float pendingTime_ = 0.0f; // секунд держится новый смысл
    float senseAge_ = 0.0f;    // секунд с принятия смысла
    bool moving_ = false;      // герой идёт (с гистерезисом)
    float movingTime_ = 0.0f;
    Framing framing_ = Framing::Standard;
    float frameX_ = 0.0f;      // где герой по ширине кадра (доля от середины)
    float shotClock_ = 0.0f;   // секунд в нынешнем приёме (смена плана в разговоре)
    int reverse_ = 0;          // разговор: 0 — двойной план, 1 — на героя, 2 — на собеседника
    Vector2 panEye_{};         // панорама: глаз стоит здесь
    float doorDistance_ = 0.0f; // кадр через проём: от героя до глаза, метры; 0 — нет
    bool shoulderBlocked_ = false; // через плечо заслонено: до склейки — двойной план
    float shoulderTime_ = 0.0f;    // секунд, как заслонено через плечо
};


#pragma once

namespace lw {

class World;

// Отношения людей во времени (этап 6.2, правила — sim/Relations.h).
//
// Раз в игровую минуту каждый неспящий человек, который стоит на месте,
// смотрит, кто рядом (до 20 м) тоже не спит и стоит: с тремя ближайшими он
// знакомится или лучше узнаёт их. В разговоре (кто-то из двоих выполняет
// «Общение») — впятеро быстрее, чем просто рядом. Знакомство растёт к 1,
// симпатия тянется к совместимости характеров (долг поднимает цель, обида
// опускает), доверие — вслед за симпатией и знакомством, пока его не срезает
// обида. Кого не видел больше двух суток, понемногу забывает. Долг и обида
// угасают сами, обида у злопамятного — дольше. Стал другом или невзлюбил —
// событие летописи.

// Изменение отношений за minutes игровых минут; шаг может быть больше минуты.
void updateRelations(World& world, float minutes);

// Вызывается каждый тик; раз в игровую минуту меняет отношения на минуту.
void tickRelations(World& world);

} // namespace lw

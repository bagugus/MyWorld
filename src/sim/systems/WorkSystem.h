// Мирная жизнь (этап 7.2), раз в игровую минуту — до решений людей:
// - кто из работников на месте (Workplace::onDuty): магазин открыт, в больнице
//   лечат, пока это не ноль;
// - раз в час — плата тем, кто на месте; урожай на фермах, где работают;
//   водопровод доливает воду в жильё;
// - раз в сутки, в kRestockHour, — завоз в магазины и больницы, где есть
//   работники (в деревенский магазин — сначала урожай своих ферм), касса
//   сдаётся; пособие тем, у кого нет работы.
// Плата, пособие, водопровод и завоз — пока их держит фаза мира (этап 7.4,
// sim/Scenario.h): в панике завоз вполовину, с коллапсом нет ничего.
// Рандома нет. Подробности и числа — docs/architecture.md, «Мирная жизнь».

inline constexpr int kRestockHour = 6;

// Сколько урожая (порций еды) фермер растит за час работы в этот сезон.

#pragma once

#include "sim/Components.h"

#include <entt/entt.hpp>

#include <cstddef>

namespace lw {

class World;

// Группы людей (этап 6.4). Группа — сущность Group без позиции: вожак,
// участники, база (общий дом) и когда собралась. У участника — Person::group.
// Подробности и числа — в docs/architecture.md, раздел «Группы».
//
// Раз в игровой час, группы — по возрастанию id:
// - погибшие и обратившиеся выбывают; нет вожака — его место занимает
//   участник с самым большим авторитетом;
// - кому вожак стал неприятен, уходит; кого невзлюбил вожак или не терпит
//   группа, того вожак изгоняет (изгнанный запоминает это и держит обиду);
// - вожаком становится тот, за кем идут: авторитет — лидерство и доверие
//   остальных; кто заметно авторитетнее вожака — смещает его;
// - меньше двух — группа распадается.
// Затем собираются новые: человек с лидерством и взаимный друг, которые
// доверяют друг другу, — и в группы вступают друзья участников. Вступивший
// переезжает на базу (дом вожака): там общие запасы, а уйдя, он вернётся в
// свой прежний дом. Рандома нет.

inline constexpr std::size_t kMaxGroupSize = 8;

// В одной ли группе a и b (оба в какой-то группе).
bool sameGroup(const entt::registry& registry, entt::entity a, entt::entity b);

// Авторитет участника: лидерство + 0,5 × среднее доверие к нему остальных
// участников (не знают — ноль).
float authorityOf(const World& world, const Group& group, EntityId member);

// Человек deserter сбежал из группы, прихватив items вещей с базы (этап 6.5):
// уходит в свой прежний дом (не было — остаётся без крова), остальные узнают
// и считают его предателем (MemoryKind::Betrayed). Сбежал вожак — группу
// сразу ведёт самый авторитетный; меньше двух — распадётся при обновлении.
void desertGroup(World& world, entt::entity deserter, int items);

// Одно обновление групп; зовёт tickGroups раз в игровой час.
void updateGroups(World& world);

// Вызывается каждый тик; раз в игровой час — updateGroups.
void tickGroups(World& world);

} // namespace lw

namespace lw {

class World;

// Бой (этап 5.4). Подробности и числа — в docs/architecture.md, раздел «Бой».
//
// Кого бить, решают другие системы — они ставят Combat::target: зомби бьёт
// догнанного, человек дерётся с зомби или стреляет в дичь, кабан бросается
// на обидчика. Здесь каждый тик тот, чьё оружие готово, а цель в
// досягаемости, бьёт или стреляет:
// - ближний бой — цель не дальше досягаемости оружия;
// - выстрел — цель не дальше предела оружия и на линии видимости (здание
//   закрывает, лес съедает дальность, как у зрения); шанс попасть падает с
//   дистанцией и в темноте; выстрел тратит патрон и слышен далеко (разовый
//   звук SoundKind::Gunshot: зомби идут на него).
// Попадание отнимает здоровье (у человека — Needs::health, у зомби и
// животных — их health), человеку ещё и открывает кровотечение (Wounds), а
// удар зомби может оказаться укусом. Раненый человек кричит (SoundKind::Scream).
// Здоровье дошло до нуля — смерть (sim/Death.h): существо становится телом.
// Рандом — поток RngStream::Combat.

// Атака существа: оружие человека, когти зомби, клыки кабана; nullptr — не бьёт.
struct AttackSpec;
const AttackSpec* attackOf(const entt::registry& registry, entt::entity attacker);

// Здоровье существа (0..1) или nullptr, если это не существо.
float* healthOf(entt::registry& registry, entt::entity entity);

void updateCombat(World& world);

} // namespace lw

#pragma once

namespace lw {

class World;

// Нужды людей: рост и спад голода, жажды, усталости, страха и одиночества,
// здоровье. Скорости заданы в игровых часах (sim/TimeScale.h).
//
// Голод доходит до предела за двое суток, жажда — за 30 часов, усталость — за
// 18 часов бодрствования (в пути быстрее). Во сне голод и жажда растут вдвое
// медленнее, усталость уходит за 7 часов дома и за 10 — под открытым небом.
// Страх тянется к уровню, который задаёт обстановка: темнота вдали от дома в
// одиночку, плохое здоровье. Одиночество растёт, когда рядом никого нет, и
// быстро уходит в компании. На пределе голода, жажды или усталости уходит
// здоровье; когда нужды в норме — оно восстанавливается.

// Изменение нужд за minutes игровых минут. Шаг может быть больше минуты
// (задел под грубую симуляцию вдали): скорости в нём постоянны.
void updateNeeds(World& world, float minutes);

// Вызывается каждый тик; раз в игровую минуту меняет нужды на минуту.
void tickNeeds(World& world);

} // namespace lw

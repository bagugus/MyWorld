#pragma once

namespace lw {

class World;

// Уровни детализации, LOD (этап 6а; правила — sim/Lod.h). Раз в
// kLodPeriodTicks пересчитывает карту активности по позициям и состояниям
// существ и ставит каждому существу уровень (компонент Lod): люди, зомби,
// звери, стаи птиц. Идёт в тике до восприятия: в этом тике все системы видят
// одни и те же уровни. Без LOD (WorldConfig::lod = false) — ничего не делает:
// компонентов Lod нет, все на полном уровне, мир тот же, что до этапа 6а.
void updateLod(World& world);

// Разметить карту активности заново по нынешнему миру, уровни не трогая. Карта
// — производные данные: в тике она нужна только пересчёту уровней, который
// сам её и строит, а между пересчётами её читает только интерфейс (слой
// «детализация»). Загрузка мира (sim/Save.h) зовёт это, чтобы слой не был
// пустым до первого пересчёта.
void refreshActivityMap(World& world);

} // namespace lw

#pragma once

#include <entt/entt.hpp>

#include "sim/Id.h"

namespace lw {

class World;

// Семья (этап 7.3), раз в игровой час: о каждом ребёнке кто-то заботится.
//
// - Опекун жив — ребёнок живёт у него (вне группы — в его доме; в группу и из
//   неё ребёнок идёт за опекуном, это делает GroupSystem).
// - Опекуна нет (погиб, обратился): если не осталось ни одного живого
//   родителя — ребёнок осиротел (летопись Orphaned). Нового опекуна ищут так:
//   живой родитель, взрослый брат или сестра, дед или бабушка, другая взрослая
//   родня; иначе взрослый, кто ребёнка знает и к нему добр (близость и
//   альтруизм). Новый опекун берёт ребёнка к себе (TookIn), ребёнок ему
//   обязан. Никого — ребёнок остаётся сам по себе и ищут снова через час.
void updateFamilies(World& world);

// updateFamilies в начале каждого игрового часа (до групп).
void tickFamilies(World& world);

// Кто возьмёт ребёнка child к себе; kInvalidId — некому. Для тестов и
// инспектора.
EntityId chooseGuardian(const World& world, entt::entity child);

} // namespace lw

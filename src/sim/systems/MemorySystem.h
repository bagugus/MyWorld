#pragma once

namespace lw {

class World;

// Память людей во времени (этап 6.1, правила — sim/Memory.h).
//
// Раз в игровую минуту воспоминания угасают, а каждый неспящий человек не в
// доме оглядывается: тело близкого в 30 м на виду — горе (Bereaved), близкий
// среди замеченных зомби — горе (Turned). Остальное запоминается в момент
// события: спасение и нападение — в бою (CombatSystem), кража — при обыске
// (Utility AI).

// Угасание и находки за minutes игровых минут; шаг может быть больше минуты.
void updateMemories(World& world, float minutes);

// Вызывается каждый тик; раз в игровую минуту — на минуту.
void tickMemories(World& world);

} // namespace lw

#pragma once

#include "sim/Components.h"
#include "sim/TimeScale.h"

#include <entt/entt.hpp>

#include <cstdint>

namespace lw {

class World;

// Память людей о значимых событиях (этап 6.1). Человек помнит, что сделали
// другие: кто спас, кто заступился, кто бросил в беде, кто обокрал, кто из
// близких погиб или встал зомби. Воспоминание — Memory в компоненте Memories:
// с кем, при чём, когда и насколько сильно. Сила угасает (постоянная времени
// 30 суток), слабое (ниже kForgotten) забывается; новое вытесняет самое
// слабое, если мест нет.
//
// Поступки других ложатся на отношения (этап 6.2, sim/Relations.h): помощь —
// долг, обида — от кражи и бегства. Гибель близкого — горе: одиночество и
// страх. Каждое новое воспоминание — событие летописи.
//
// Узнают о событиях только сами, своими глазами: кого видят рядом (Awareness),
// кто дома застал вора, чьё тело нашли. Слухи — на следующих этапах.
//
// Рандома нет: свидетели и последствия зависят только от состояния мира.

// Ниже этой силы воспоминание забывается.
inline constexpr float kForgotten = 0.1f;
// Тот же случай (вид и человек) в пределах этого — повтор: память освежается,
// но долг, обида и летопись не растут. Позже — новый случай.
inline constexpr std::uint64_t kEpisodeTicks = kTicksPerGameHour;
// С такой близости (closeness) гибель отзывается горем, а бегство — обидой.
inline constexpr float kCloseEnough = 0.2f;

// Запомнить: занять свободное место или вытеснить самое слабое, если оно
// слабее нового. Возвращает true, если случай новый (не повтор того же в
// пределах kEpisodeTicks и место нашлось).
bool remember(Memories& memories, MemoryKind kind, EntityId who, EntityId about, float strength,
              std::uint64_t tick);

// Угасание за minutes игровых минут; забытое удаляется, порядок остальных
// сохраняется.
void fadeMemories(Memories& memories, float minutes);

// Пережить событие: запомнить и, если случай новый, — последствия для
// отношений и нужд и запись в летопись. Сила воспоминания, долг, обида и горе
// зависят от вида события, черт self и того, насколько близок ему who.
// a — подробность для летописи. Возвращает true, если случай новый.
bool experience(World& world, entt::entity self, MemoryKind kind, EntityId who, EntityId about,
                std::int32_t a = 0);

// --- Свидетели: кто что увидел ------------------------------------------------

// Человек rescuer убил зомби zombie: тот, на кого зомби нападал или за кем
// гнался, запоминает спасителя. Звать до die() — пока у зомби есть цель.
void witnessRescue(World& world, EntityId rescuer, entt::entity zombie);

// Зомби zombie ранил человека victim: кто из близких рядом убегал — бросил, кто
// дрался с напавшими на него зомби — заступился.
void witnessAttack(World& world, entt::entity victim, EntityId zombie);

// Человек thief обыскал чужое жилое здание building и взял items вещей:
// хозяева, которые это видели или были дома (не спали), запоминают вора.
void witnessTheft(World& world, entt::entity thief, EntityId building, int items);

} // namespace lw

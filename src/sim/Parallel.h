#pragma once

#include <cstddef>
#include <functional>

namespace lw {

// Параллельный проход для систем, где каждая задача пишет только свои данные
// (этап 2а.1): восприятие обновляет только Awareness своего существа, движение —
// только его позицию. Задачи делятся на куски, куски разбирают рабочие потоки и
// вызвавший поток; вызов возвращается, когда сделаны все.
//
// Детерминизм. Результат не зависит ни от числа потоков, ни от того, какой
// поток какой кусок взял, — только если задачи не пишут общего и не тянут
// рандом мира. Всё, что зависит от порядка (Rng, летопись, создание сущностей),
// в параллельный проход не попадает.
//
// Пул один на процесс и создаётся при первом использовании. Рабочие после
// прохода короткое время ждут следующего «на ходу» (на x100 проходы идут
// тысячами в секунду, и будить потоки каждый раз дороже самой работы), потом
// засыпают.

// Сколько потоков (вместе с вызывающим) можно занять: 1 — всё в вызывающем
// потоке. По умолчанию — по числу ядер, не больше kMaxParallelThreads.
inline constexpr int kMaxParallelThreads = 8;
void setParallelThreads(int threads);
int parallelThreads();

// fn(begin, end, worker) для кусков [begin, end) из [0, count) длиной не больше
// chunk; worker — номер потока 0..parallelThreads()-1 (0 — вызвавший), чтобы
// задачи брали свой рабочий буфер. Меньше minParallel задач — всё в вызывающем
// потоке.
void parallelFor(std::size_t count, std::size_t chunk, std::size_t minParallel,
                 const std::function<void(std::size_t, std::size_t, int)>& fn);

} // namespace lw

#pragma once

#include "sim/Components.h"

namespace lw {

class Rng;
class World;

// Наполнение мира при создании: лут в зданиях, люди, зомби, животные.

// Лут (Inventory) во всех зданиях. Поток рандома — RngStream::Supplies.
// Еда и вода: дом — еды 3–12 порций, воды 2–8; многоэтажка — 8–30 и 6–20;
// магазин — 20–80 и 15–50; сарай — еды до 15 (зерно, картошка), воды нет.
// Снаряжение — по таблице вида здания (docs/architecture.md, «Инвентарь и лут»):
// бинты и лекарства — в жилье и магазинах, патроны — в магазинах, ружья —
// изредка в домах и сараях; в городах снаряжения больше. Особые места: аптека
// в каждом городе, дом охотника с винтовкой — в половине деревень.
void spawnLoot(World& world);

// Поселить count человек в жилые дома (дом весит 1, многоэтажка — 4), у дверей.
// Если жилья на карте нет — на случайные проходимые клетки, без дома.
// Нужды начальные — как у людей утром, черты — generateTraits. Оружие: у
// трети — только кулаки, у половины — нож или топор, у пятой части — пистолет,
// дробовик или винтовка с несколькими патронами (поток RngStream::Combat).
// Соседи по дому и по поселению знакомы с начала (introduceNeighbours, этап 6.1).
void spawnPeople(World& world, int count);

// Расселить count зомби подальше от людей (индекс должен уже знать людей):
// четверть — орды по 12–30 вдали от поселений, остальные — одиночки: больше
// у зданий, где никто не живёт рядом, меньше на природе. Поток — RngStream::Zombies.
void spawnZombies(World& world, int count);

// Расселить count животных и flocks стай птиц (индекс должен уже знать людей):
// половина — олени стадами по 2–5, четверть — кабаны по 1–3, остальные —
// зайцы; олени и кабаны — в лесу, зайцы — в полях; все вдали от поселений и
// людей. Стаи — на любой суше не ближе 150 м к людям. Поток — RngStream::Animals.
void spawnAnimals(World& world, int count, int flocks);

// Орда из size зомби, пришедшая издалека (этап 5.7): у случайной суши не
// ближе 800 м к людям и 400 м к центрам поселений; сразу идёт дальше.
// Возвращает, сколько появилось: 0 — места не нашлось.
int spawnZombieGroup(World& world, int size, Rng& rng);

// Сколько животных вида kind из count (доли — как при расселении).
int animalTarget(int count, AnimalKind kind);
// Размер группы: стадо оленей 2–5, кабанов 1–3, заяц — один.
int animalGroupSize(AnimalKind kind, Rng& rng);
// Группа из size животных у случайного подходящего места (лес или поле)
// вдали от поселений и не ближе peopleDistance к людям. Возвращает, сколько
// появилось: 0 — места не нашлось.
int spawnAnimalGroup(World& world, AnimalKind kind, int size, float peopleDistance, Rng& rng);

} // namespace lw
